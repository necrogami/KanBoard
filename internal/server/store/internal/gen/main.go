// Command gen writes pgquerier_gen.go: a Postgres implementation of the
// SQLite-generated Querier interface. Both sqlc packages generate
// struct-identical types from the same queries, so each method is a
// type conversion in and out.
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"unicode"
)

func main() {
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, "sqlitegen/querier.go", nil, 0)
	if err != nil {
		fail(err)
	}
	var iface *ast.InterfaceType
	for _, d := range f.Decls {
		gd, ok := d.(*ast.GenDecl)
		if !ok {
			continue
		}
		for _, s := range gd.Specs {
			if ts, ok := s.(*ast.TypeSpec); ok && ts.Name.Name == "Querier" {
				iface = ts.Type.(*ast.InterfaceType)
			}
		}
	}
	if iface == nil {
		fail(fmt.Errorf("querier interface not found"))
	}

	var b bytes.Buffer
	b.WriteString("// Code generated by go run ./internal/gen; DO NOT EDIT.\n\n")
	b.WriteString("package store\n\nimport (\n\t\"context\"\n\t\"database/sql\"\n\n")
	b.WriteString("\t\"github.com/necrogami/kanboard/internal/server/store/pggen\"\n")
	b.WriteString("\t\"github.com/necrogami/kanboard/internal/server/store/sqlitegen\"\n)\n\n")
	b.WriteString("var _ = sql.ErrNoRows\n\n")
	b.WriteString("type pgQuerier struct{ q *pggen.Queries }\n\n")
	b.WriteString("func newPGQuerier(db pggen.DBTX) Querier { return &pgQuerier{q: pggen.New(db)} }\n\n")

	for _, m := range iface.Methods.List {
		ft := m.Type.(*ast.FuncType)
		name := m.Names[0].Name
		argSig, argCall := "", ""
		if len(ft.Params.List) == 2 {
			at := ft.Params.List[1].Type
			argSig = ", arg " + typeStr(at, "sqlitegen")
			argCall = ", " + conv("arg", at, "pggen")
		}
		results := ft.Results.List
		if len(results) == 1 {
			fmt.Fprintf(&b, "func (a *pgQuerier) %s(ctx context.Context%s) error {\n\treturn a.q.%s(ctx%s)\n}\n\n", name, argSig, name, argCall)
			continue
		}
		rt := results[0].Type
		resSig := typeStr(rt, "sqlitegen")
		if arr, ok := rt.(*ast.ArrayType); ok && isGenerated(arr.Elt) {
			elem := typeStr(arr.Elt, "sqlitegen")
			fmt.Fprintf(&b, "func (a *pgQuerier) %s(ctx context.Context%s) (%s, error) {\n", name, argSig, resSig)
			fmt.Fprintf(&b, "\trs, err := a.q.%s(ctx%s)\n\tif err != nil {\n\t\treturn nil, err\n\t}\n", name, argCall)
			fmt.Fprintf(&b, "\tout := make([]%s, len(rs))\n\tfor i := range rs {\n\t\tout[i] = %s(rs[i])\n\t}\n\treturn out, nil\n}\n\n", elem, elem)
			continue
		}
		fmt.Fprintf(&b, "func (a *pgQuerier) %s(ctx context.Context%s) (%s, error) {\n", name, argSig, resSig)
		fmt.Fprintf(&b, "\tr, err := a.q.%s(ctx%s)\n\treturn %s, err\n}\n\n", name, argCall, conv("r", rt, "sqlitegen"))
	}

	src, err := format.Source(b.Bytes())
	if err != nil {
		fail(fmt.Errorf("format: %w\n%s", err, b.String()))
	}
	if err := os.WriteFile("pgquerier_gen.go", src, 0o644); err != nil {
		fail(err)
	}
}

// isGenerated reports whether t is a type defined in the sqlc package
// (exported identifier) rather than a builtin or imported type.
func isGenerated(t ast.Expr) bool {
	id, ok := t.(*ast.Ident)
	return ok && unicode.IsUpper(rune(id.Name[0]))
}

func typeStr(t ast.Expr, pkg string) string {
	switch x := t.(type) {
	case *ast.Ident:
		if isGenerated(x) {
			return pkg + "." + x.Name
		}
		return x.Name
	case *ast.SelectorExpr:
		return typeStr(x.X, pkg) + "." + x.Sel.Name
	case *ast.ArrayType:
		return "[]" + typeStr(x.Elt, pkg)
	}
	fail(fmt.Errorf("unsupported type %T", t))
	return ""
}

func conv(expr string, t ast.Expr, pkg string) string {
	if isGenerated(t) {
		return pkg + "." + t.(*ast.Ident).Name + "(" + expr + ")"
	}
	return expr
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "gen:", err)
	os.Exit(1)
}
